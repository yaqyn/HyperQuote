/**
 * Quote request server functions.
 * Submit, save draft, get drafts, and AI-assisted parsing.
 * Dev mode fallback when Supabase not configured.
 */
import { createServerFn } from '@tanstack/react-start'
import { z } from 'zod'
import { getServerSession } from '@hyperquote/auth'

// ============================================================================
// Input Schemas
// ============================================================================

const quoteItemSchema = z.object({
  productId: z.string().uuid().optional(),
  customerDescription: z.string().min(1),
  quantity: z.number().positive(),
  unitOfMeasure: z.string(),
  notes: z.string().optional(),
  sortOrder: z.number(),
  matchConfidence: z.number().optional(),
  isUnmatched: z.boolean().optional(),
})

const submitQuoteRequestInput = z.object({
  items: z.array(quoteItemSchema).min(1),
  deliveryAddressId: z.string().uuid().optional(),
  deliveryDate: z.string().optional(),
  notes: z.string().optional(),
  projectId: z.string().uuid().optional(),
  attachmentUrls: z.array(z.string()).optional(),
  approvalRequired: z.boolean().optional(),
  idempotencyKey: z.string().uuid(),
})

const saveDraftInput = z.object({
  draftId: z.string().uuid().optional(),
  items: z.array(quoteItemSchema),
  deliveryAddressId: z.string().uuid().optional(),
  deliveryDate: z.string().optional(),
  notes: z.string().optional(),
  projectId: z.string().uuid().optional(),
  attachmentUrls: z.array(z.string()).optional(),
})

const parseWithAIInput = z.object({
  text: z.string().min(1),
})

// ============================================================================
// Types
// ============================================================================

export interface ParsedItem {
  productName: string
  quantity: number
  unitOfMeasure: string
  notes?: string
  matchConfidence: number
}

// ============================================================================
// Helper: check if Supabase is configured
// ============================================================================

function isSupabaseConfigured(): boolean {
  return !!(
    process.env.SUPABASE_URL &&
    process.env.SUPABASE_URL !== 'https://placeholder.supabase.co' &&
    process.env.SUPABASE_ANON_KEY &&
    process.env.SUPABASE_ANON_KEY !== 'placeholder'
  )
}

// ============================================================================
// submitQuoteRequest
// ============================================================================

export const submitQuoteRequest = createServerFn()
  .inputValidator(submitQuoteRequestInput)
  .handler(
    async ({
      data: input,
    }): Promise<{ requestId: string; reference: string }> => {
      // Dev mode fallback
      if (!isSupabaseConfigured()) {
        const mockId = crypto.randomUUID()
        const year = new Date().getFullYear()
        const seq = String(Math.floor(Math.random() * 99999)).padStart(5, '0')
        return {
          requestId: mockId,
          reference: `QR-${year}-${seq}`,
        }
      }

      const session = await getServerSession({
        supabaseUrl: process.env.SUPABASE_URL!,
        supabaseAnonKey: process.env.SUPABASE_ANON_KEY!,
      })

      if (!session) {
        throw new Error('Unauthorized')
      }

      // Dynamic import to keep Supabase off the client bundle
      const { createClient } = await import('@supabase/supabase-js')
      const supabase = createClient(
        process.env.SUPABASE_URL!,
        process.env.SUPABASE_ANON_KEY!,
        {
          global: {
            headers: { Authorization: `Bearer ${session.session.access_token}` },
          },
        },
      )

      // Check idempotency
      const { data: existing } = await supabase
        .from('quote_requests')
        .select('id, request_number')
        .eq('idempotency_key', input.idempotencyKey)
        .maybeSingle()

      if (existing) {
        return {
          requestId: existing.id,
          reference: existing.request_number,
        }
      }

      const status = input.approvalRequired ? 'draft' : 'submitted'
      const submittedAt = input.approvalRequired ? null : new Date().toISOString()

      // Insert quote request (request_number auto-generated by trigger)
      const { data: qr, error: qrError } = await supabase
        .from('quote_requests')
        .insert({
          customer_id: session.user.app_metadata?.customer_id,
          status,
          urgency: 'standard',
          project_id: input.projectId ?? null,
          delivery_address_id: input.deliveryAddressId ?? null,
          delivery_date: input.deliveryDate ?? null,
          notes: input.notes ?? null,
          attachment_urls: input.attachmentUrls ?? [],
          submitted_at: submittedAt,
          submitted_by: session.user.id,
          idempotency_key: input.idempotencyKey,
          approval_required: input.approvalRequired ?? false,
        })
        .select('id, request_number')
        .single()

      if (qrError || !qr) {
        throw new Error(qrError?.message ?? 'Failed to create quote request')
      }

      // Insert items
      const itemRows = input.items.map((item) => ({
        quote_request_id: qr.id,
        product_id: item.productId ?? null,
        customer_description: item.customerDescription,
        quantity: item.quantity,
        unit_of_measure: item.unitOfMeasure,
        notes: item.notes ?? null,
        match_confidence: item.matchConfidence ?? null,
        sort_order: item.sortOrder,
        is_unmatched: item.isUnmatched ?? false,
      }))

      const { error: itemsError } = await supabase
        .from('quote_request_items')
        .insert(itemRows)

      if (itemsError) {
        throw new Error(itemsError.message)
      }

      // If approval required, create approval record
      if (input.approvalRequired) {
        await supabase.from('approvals').insert({
          approval_type: 'quote_discount',
          entity_type: 'quote_request',
          entity_id: qr.id,
          requested_by: session.user.id,
          assigned_to: session.user.id, // Placeholder; real approver assigned by workflow
          status: 'pending',
          context: { items_count: input.items.length },
        })
      }

      return {
        requestId: qr.id,
        reference: qr.request_number,
      }
    },
  )

