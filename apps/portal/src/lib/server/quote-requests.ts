export const parseWithAI = createServerFn()
  .inputValidator(parseWithAIInput)
  .handler(
    async ({
      data: input,
    }): Promise<{ parsedItems: ParsedItem[] }> => {
      // Mock implementation: extract quantities and materials from text
      const lines = input.text
        .split('\n')
        .map((l) => l.trim())
        .filter(Boolean)
      const parsedItems: ParsedItem[] = []

      for (const line of lines) {
        const lower = line.toLowerCase()
        // Try to extract quantity (any number in the line)
        const qtyMatch = line.match(/(\d+(?:\.\d+)?)\s*(?:ton|kg|m|pcs?|bags?|sheets?)?/i)
        const quantity = qtyMatch ? parseFloat(qtyMatch[1]) : 1

        // Find matching material keyword
        let matched = false
        for (const [keyword, material] of Object.entries(MATERIAL_KEYWORDS)) {
          if (lower.includes(keyword)) {
            parsedItems.push({
              productName: material.name,
              quantity,
              unitOfMeasure: material.uom,
              notes: line,
              matchConfidence: 0.8,
            })
            matched = true
            break
          }
        }

        // If no keyword matched, add as unmatched
        if (!matched && line.length > 2) {
          parsedItems.push({
            productName: line,
            quantity,
            unitOfMeasure: 'piece',
            notes: line,
            matchConfidence: 0.3,
          })
        }
      }

      return { parsedItems }
    },
  )
